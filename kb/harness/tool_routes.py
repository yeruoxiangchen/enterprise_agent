"""Typed public tool interfaces resolved to the existing business catalogue.

The model chooses a business operation; backend permission labels are derived
from the same catalogue used by the service, not generated by the model.
"""
from copy import deepcopy
from dataclasses import dataclass
from typing import Callable
import re

from .contracts import ToolSpec


@dataclass(frozen=True)
class ToolRoute:
    public_spec: ToolSpec
    target: str
    resolve: Callable[[dict], dict]
    parameters_for_request: Callable[[], dict] | None = None
    describe_result: Callable[[dict, dict], str | None] | None = None


def operation_permission_route(port):
    from kb.benchmark.crm_contract import PERMISSION_ALIASES

    source = next(spec for spec in port.tools() if spec.name == 'check_permission')
    available = {spec.name for spec in port.tools()}
    labels = source.parameters['properties']['action'].get('enum', [])
    mapping = {name: label for name, label in PERMISSION_ALIASES.items()
               if name in available and (not labels or label in labels)}
    parameters = deepcopy(source.parameters)
    parameters['properties'].pop('action')
    parameters['properties']['operation'] = {
        'type': 'string', 'enum': sorted(mapping),
        'description': 'The actual requested business operation, such as close_ticket or delete_ticket.',
    }
    parameters['required'] = ['operation' if key == 'action' else key
                              for key in parameters.get('required', [])]
    public = ToolSpec('check_operation_permission',
        "Check the supplied user's permission for the requested operation on a ticket. "
        'Use the operation name directly; backend permission labels are resolved by the service. '
        'This is a read-only permission assessment and never performs the operation.',
        parameters, source.domain)

    def resolve(arguments):
        return {**{key: value for key, value in arguments.items() if key != 'operation'},
                'action': mapping[arguments['operation']]}

    def current_parameters():
        """Constrain account identifiers to the existing source identity gate.

        This uses actual account IDs already supplied in the conversation or
        authenticated session, not a model-generated identity extraction.
        """
        schema = deepcopy(parameters)
        state = port.environment.get_state()
        supplied = '\n'.join(port.user_messages)
        principal = state.get('session', {}).get('user_id')
        candidates = [identity for identity in state.get('users', {})
            if identity == principal or re.search(
                r'(?<![\w.@-])'+re.escape(identity)+r'(?![\w@-]|\.[\w])', supplied)]
        if candidates:
            schema['properties']['user_id']['enum'] = sorted(candidates)
        return schema

    def describe_result(result, arguments):
        value = result.get('value')
        if result.get('status') != 'observed' or not isinstance(value, dict) or value.get('allowed') is not False:
            return None
        return (f"{value['user_id']} is not permitted to perform {arguments['operation']} "
                f"on ticket {value['ticket_id']}. This is the completed permission assessment.")

    return ToolRoute(public, source.name, resolve, current_parameters, describe_result)
